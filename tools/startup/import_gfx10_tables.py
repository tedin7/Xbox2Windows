"""Regenerate the C++ GFX10 name tables from the pinned Mesa-derived Victory tables."""
import argparse
import hashlib
import os
from pathlib import Path
import re
import sys
import tempfile

_TOOLS_DIR = str(Path(__file__).resolve().parents[1])
if _TOOLS_DIR not in sys.path:
    sys.path.insert(0, _TOOLS_DIR)
import disasm_rdna2 as x2w

SHA256 = "1ee1228584a611b26cae949efb248fe00fd5e835a550353cc1d33c2f7c262acc"
TABLES = ("SOPP", "SOP1", "SOP2", "SOPC", "SOPK", "VOP1", "VOP2", "VOPC",
          "VOP3", "VOP3P", "VINTRP", "SMEM", "MUBUF", "MTBUF", "MIMG", "DS",
          "FLAT", "GLOBAL", "SCRATCH")


def _validate_source_file(source: Path) -> None:
    if source.is_dir():
        raise IsADirectoryError(f"opcodes.rs path is a directory: {source}")
    if not source.exists():
        raise FileNotFoundError(f"opcodes.rs file not found: {source}")
    if not source.is_file():
        raise ValueError(f"opcodes.rs path is not a regular file: {source}")


def _validate_paths(opcodes_rs: Path, output: Path) -> None:
    _validate_source_file(opcodes_rs)
    if output.is_symlink():
        raise ValueError(f"output path must not be a symlink: {output}")
    if output.is_dir():
        raise IsADirectoryError(f"output path is a directory: {output}")
    for parent in output.parents:
        if parent.is_file() or ((parent.exists() or parent.is_symlink()) and not parent.is_dir()):
            raise NotADirectoryError(f"output parent is not a directory: {parent}")
    if output.resolve() == opcodes_rs.resolve() or (output.exists() and opcodes_rs.samefile(output)):
        raise ValueError(f"output path must differ from opcodes.rs input: {output}")


def _write_atomic(path: Path, content: str) -> None:
    """Write UTF-8 text to a sibling temp file and atomically replace path, leaving 0 temp files on failure."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=path.parent,
            prefix=f".{path.stem}.",
            suffix=".tmp",
            delete=False,
        ) as handle:
            tmp_path = Path(handle.name)
            handle.write(content)
        os.replace(tmp_path, path)
    except BaseException:
        if tmp_path is not None:
            tmp_path.unlink(missing_ok=True)
        raise


def generate(source, expected_sha256=SHA256):
    """Parse pinned opcodes.rs and merge X2W disassembler additions into C++ table arrays."""
    source_path = Path(source)
    _validate_source_file(source_path)
    data = source_path.read_bytes().replace(b"\r\n", b"\n")
    if hashlib.sha256(data).hexdigest() != expected_sha256:
        raise ValueError("expected victory-shader gfx10/opcodes.rs at 9376fd6")
    rust = data.decode("utf-8")
    marker = "// Each table"
    marker_idx = rust.find(marker)
    if marker_idx == -1:
        raise ValueError(f"missing {marker!r} marker in {source_path}")
    notice = rust[:marker_idx]
    out = [notice, "// Generated by tools/startup/import_gfx10_tables.py.\n"
           "// The secondary entries come from X2W's gfx1013 disassembler.\n"]
    total = extra = 0
    for table in TABLES:
        match = re.search(r"const " + table + r": [^=]+?= &\[(.*?)\];", rust, re.S)
        if match is None:
            raise ValueError(f"missing {table} table in {source_path}")
        entries = {int(op, 16): name for op, name in re.findall(r'\(0x([0-9a-f]+), "(\w+)"\)', match.group(1))}
        if not entries:
            raise ValueError(f"empty {table} table in {source_path}")
        total += len(entries)
        local = getattr(x2w, table + "_OPS", {})
        if table == "VOP3":
            local = {**x2w.VOP3_NATIVE_OPS, **x2w.INTERP_F16_OPS}
        if table == "MIMG":
            local = {**local, **x2w.MIMG_BVH_OPS}
        for op, info in local.items():
            name = info if isinstance(info, str) else info[0]
            if op not in entries and isinstance(name, str) and re.fullmatch(r"\w+", name):
                entries[op] = re.sub(r"_e(?:32|64)$", "", name)
                extra += 1
        out.append(f"constexpr const char* {table.lower()}_names[] = {{")
        for offset in range(0, max(entries) + 1, 4):
            row = [f'"{entries[i]}"' if i in entries else "nullptr"
                   for i in range(offset, min(offset + 4, max(entries) + 1))]
            out.append("    " + ", ".join(row) + ",")
        out.append("};\n")
    print(f"Imported {total} Mesa/Victory entries and {extra} X2W additions")
    return "\n".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("opcodes_rs", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args(argv)
    try:
        _validate_paths(args.opcodes_rs, args.output)
        _write_atomic(args.output, generate(args.opcodes_rs, expected_sha256=SHA256))
    except (OSError, ValueError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

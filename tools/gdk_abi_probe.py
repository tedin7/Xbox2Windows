#!/usr/bin/env python3
"""Generate and compare C++ ABI probes from parsed GDK layouts.

The layout JSON comes from tools/gdk_layouts.py. The generated probe can either
assert sizes and offsets at compile time or print them for a GRDK/GXDK diff.
Only names, sizes and offsets are used; private members and non-standard-layout
classes need an explicit review before offsetof is enabled.

Commands:
  generate --layouts <json> --out <cpp> [--include H]... [--print] [--offsetof]
  parse <log> [--json <out>]
  diff <left.json> <right.json>
"""

import argparse
import json
import re
import sys
from pathlib import Path


IDENTIFIER = re.compile(r"^[A-Za-z_]\w*$")
CLASS_NAME = re.compile(r"^(?:::)?[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*$")


def load_classes(path):
    document = json.loads(Path(path).read_text(encoding="utf-8"))
    return document, document.get("classes", [])


def member_offsets(block):
    has_dynamic_layout = bool(block.get("bases")) or any(
        item.get("kind") == "vftable" for item in block.get("members", [])
    )
    if has_dynamic_layout:
        return []
    offsets = []
    for item in block.get("members", []):
        if item.get("kind") != "field" or item.get("bits") is not None:
            continue
        name = item.get("name", "")
        if IDENTIFIER.fullmatch(name):
            offsets.append((name, item["offset"]))
    return offsets


def generate_command(args):
    document, classes = load_classes(args.layouts)
    if args.prefix:
        classes = [
            block
            for block in classes
            if any(block["name"].startswith(prefix) for prefix in args.prefix)
        ]
    skipped = [block["name"] for block in classes if not CLASS_NAME.fullmatch(block["name"])]
    classes = [block for block in classes if CLASS_NAME.fullmatch(block["name"])]
    lines = [
        "// Generated by tools/gdk_abi_probe.py; do not edit.",
        f"// module: {document.get('module', '')}",
        f"// source: {document.get('header', '')}",
        "",
    ]
    lines += [f"#include <{header}>" if not header.startswith('"') else f"#include {header}" for header in args.include]
    lines.append("#include <cstddef>")
    if args.print:
        lines.append("#include <cstdio>")
    lines.append("")
    for block in classes:
        name = block["name"]
        lines.append(f'static_assert(sizeof({name}) == {block["size"]}, "sizeof({name})");')
        if args.offsetof:
            for member, offset in member_offsets(block):
                lines.append(
                    f'static_assert(offsetof({name}, {member}) == {offset}, "offsetof({name}, {member})");'
                )
    if args.print:
        lines += ["", "int main()", "{"]
        for block in classes:
            name = block["name"]
            lines.append(f'    std::printf("sizeof({name})=%zu\\n", sizeof({name}));')
            if args.offsetof:
                for member, _ in member_offsets(block):
                    lines.append(
                        f'    std::printf("offsetof({name}, {member})=%zu\\n", offsetof({name}, {member}));'
                    )
        lines += ["    return 0;", "}"]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(
        json.dumps(
            {
                "classes": len(classes),
                "skipped": len(skipped),
                "offsetof": bool(args.offsetof),
                "print": bool(args.print),
            }
        )
    )
    return 0


def parse_command(args):
    facts = {}
    for line in Path(args.log).read_text(encoding="utf-8", errors="replace").splitlines():
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        try:
            facts[key.strip()] = int(value.strip(), 0)
        except ValueError:
            facts[key.strip()] = value.strip()
    document = {"facts": facts}
    if args.json:
        Path(args.json).parent.mkdir(parents=True, exist_ok=True)
        Path(args.json).write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"facts": len(facts)}))
    return 0


def diff_command(args):
    left = json.loads(Path(args.left).read_text(encoding="utf-8")).get("facts", {})
    right = json.loads(Path(args.right).read_text(encoding="utf-8")).get("facts", {})
    changes = []
    for key in sorted(set(left) | set(right)):
        if left.get(key) != right.get(key):
            changes.append({"key": key, "left": left.get(key), "right": right.get(key)})
    if not changes:
        print("no ABI differences")
        return 0
    for change in changes:
        print(json.dumps(change, sort_keys=True))
    return 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    generate = sub.add_parser("generate", help="emit a C++ probe")
    generate.add_argument("--layouts", required=True)
    generate.add_argument("--out", required=True)
    generate.add_argument("--include", action="append", default=[])
    generate.add_argument("--prefix", action="append", default=[])
    generate.add_argument("--offsetof", action="store_true")
    generate.add_argument("--print", action="store_true")
    generate.set_defaults(func=generate_command)

    parse = sub.add_parser("parse", help="parse a probe log")
    parse.add_argument("log")
    parse.add_argument("--json")
    parse.set_defaults(func=parse_command)

    diff = sub.add_parser("diff", help="compare two parsed probe logs")
    diff.add_argument("left")
    diff.add_argument("right")
    diff.set_defaults(func=diff_command)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())

            self.assertEqual([p.name for p in out_dir.iterdir()], ["gfx1013_isa_tables.inl"])

            # Temp write failure (e.g. disk full) unlinks temp file and preserves original output.
            with (
                mock.patch.object(import_gfx10_tables, "SHA256", digest),
                mock.patch.object(import_gfx10_tables, "generate", return_value="NEW_CONTENT"),
            ):
                real_ntf = tempfile.NamedTemporaryFile

                def failing_ntf(*args, **kwargs):
                    handle = real_ntf(*args, **kwargs)
                    orig_write = handle.write

                    def boom(_text):
                        raise OSError("simulated disk full")

                    handle.write = boom
                    handle._orig_write = orig_write
                    return handle

                with mock.patch.object(import_gfx10_tables.tempfile, "NamedTemporaryFile", side_effect=failing_ntf):
                    self._assert_clean_failure(
                        [str(rs_path), str(out_inl)],
                        expected_code=1,
                        fragments=("simulated disk full",),
                        check_subprocess=False,
                    )

            self.assertEqual(out_inl.read_text(encoding="utf-8"), "ORIGINAL_CONTENT")
            self.assertEqual([p.name for p in out_dir.iterdir()], ["gfx1013_isa_tables.inl"])


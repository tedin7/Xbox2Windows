def _build_synthetic_opcodes_rs(
    *,
    notice: str = "// Synthetic Mesa GFX10 notice\n//\n\n",
    include_marker: bool = True,
    omit_table: str | None = None,
    empty_table: str | None = None,
    overrides: dict[str, list[tuple[int, str]]] | None = None,
) -> str:
    parts = [notice]
    if include_marker:
        parts.append("// Each table maps opcode index to mnemonic.\n\n")
    custom = overrides or {}
    for idx, table in enumerate(import_gfx10_tables.TABLES):
        if table == omit_table:
            continue
        if table == empty_table:
            body = ""
        else:
            rows = custom.get(table, [(idx & 0x3, f"syn_{table.lower()}_{idx}")])
            body = "\n".join(f'    (0x{op:02x}, "{name}"),' for op, name in rows)
            if body:
                body = "\n" + body + "\n"
        parts.append(f"const {table}: &[(u16, &str)] = &[{body}];\n")
    return "".join(parts)


def _sha256_lf(raw: bytes) -> str:
    return hashlib.sha256(raw.replace(b"\r\n", b"\n")).hexdigest()


def _run_main(module, argv: list[str] | None) -> tuple[int, str, str]:
    stdout = io.StringIO()
    stderr = io.StringIO()
    with redirect_stdout(stdout), redirect_stderr(stderr):
        try:
            code = module.main(argv)
        except SystemExit as exc:
            code = exc.code
            if not isinstance(code, int):
                if code is not None:
                    stderr.write(f"{code}\n")
                code = 0 if code is None else 1
    return code, stdout.getvalue(), stderr.getvalue()


def _run_subprocess(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-B", str(TOOL), *args],
        capture_output=True,
        text=True,
        timeout=30,
    )


def _tmp_files(directory: Path) -> list[Path]:
    return [p for p in directory.iterdir() if p.suffix == ".tmp"]


class ImportGfx10TablesPositiveTests(unittest.TestCase):
    def test_synthetic_merge_strips_e32_e64_preserves_existing_and_writes_atomically(self) -> None:
        # Leave opcodes 0x01 in VOP1/VOP2 and 0x128 in VOP3 absent so disasm_rdna2 fills them
        # and strips _e32 / _e64, while pinning 0x00 in SOPP to verify existing entries win.
        overrides = {
            "SOPP": [(0x00, "custom_nop_keep")],
            "VOP1": [(0x00, "v_nop")],
            "VOP2": [(0x03, "v_add_f32")],
            "VOP3": [(0x140, "v_mad_legacy_f32")],
            "VINTRP": [(0x00, "v_interp_p1_f32"), (0x02, "v_interp_mov_f32")],
            "SMEM": [(0x01, "s_load_dwordx2")],
            "MIMG": [(0x00, "image_load")],
        }
        notice = "// Synthetic notice header\n// Line 2\n\n"
        text = _build_synthetic_opcodes_rs(notice=notice, overrides=overrides)
        raw_crlf = text.replace("\n", "\r\n").encode("utf-8")
        digest = _sha256_lf(raw_crlf)

        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            rs_path = base / "opcodes.rs"
            rs_path.write_bytes(raw_crlf)
            nested_out = base / "nested" / "sub" / "gfx1013_isa_tables.inl"
            self.assertFalse(nested_out.parent.exists())

            direct_out = io.StringIO()
            with redirect_stdout(direct_out):
                generated = import_gfx10_tables.generate(rs_path, expected_sha256=digest)

            self.assertTrue(generated.startswith(notice))
            self.assertIn("// Generated by tools/startup/import_gfx10_tables.py.", generated)
            self.assertNotIn("\r", generated)

            # Existing opcodes.rs entry is preserved over disasm_rdna2 SOPP_OPS[0x00] = "s_nop".
            sopp_block = re.search(r"constexpr const char\* sopp_names\[\] = \{(.*?)\};", generated, re.S)
            self.assertIsNotNone(sopp_block)
            self.assertIn('"custom_nop_keep"', sopp_block.group(1))
            self.assertIn('"s_endpgm"', sopp_block.group(1))

            # VOP1_OPS[0x01] = "v_mov_b32_e32" -> "v_mov_b32"; VOP2_OPS[0x01] = "v_cndmask_b32_e32" -> "v_cndmask_b32".
            vop1_block = re.search(r"constexpr const char\* vop1_names\[\] = \{(.*?)\};", generated, re.S)
            vop2_block = re.search(r"constexpr const char\* vop2_names\[\] = \{(.*?)\};", generated, re.S)
            self.assertIn('"v_mov_b32"', vop1_block.group(1))
            self.assertNotIn("_e32", vop1_block.group(1))
            self.assertIn('"v_cndmask_b32"', vop2_block.group(1))
            self.assertNotIn("_e32", vop2_block.group(1))

            # VOP3_NATIVE_OPS[0x128] = "v_add_co_ci_u32_e64" -> "v_add_co_ci_u32" and INTERP_F16_OPS merged.
            vop3_block = re.search(r"constexpr const char\* vop3_names\[\] = \{(.*?)\};", generated, re.S)
            self.assertIn('"v_add_co_ci_u32"', vop3_block.group(1))
            self.assertIn('"v_interp_p1ll_f16"', vop3_block.group(1))
            self.assertNotIn("_e64", vop3_block.group(1))

            # MIMG_BVH_OPS merged into MIMG and SMEM string entries imported.
            mimg_block = re.search(r"constexpr const char\* mimg_names\[\] = \{(.*?)\};", generated, re.S)
            smem_block = re.search(r"constexpr const char\* smem_names\[\] = \{(.*?)\};", generated, re.S)
            self.assertIn('"image_bvh_intersect_ray"', mimg_block.group(1))
            self.assertIn('"s_load_dword"', smem_block.group(1))

            # VINTRP has no disasm_rdna2 table and gap at index 1 emits nullptr.
            vintrp_block = re.search(r"constexpr const char\* vintrp_names\[\] = \{(.*?)\};", generated, re.S)
            self.assertIn('"v_interp_p1_f32", nullptr, "v_interp_mov_f32"', vintrp_block.group(1))

            # Verify expected X2W addition count matches summary stdout.
            expected_tables = {t for t in import_gfx10_tables.TABLES}
            self.assertEqual(len(expected_tables), len(import_gfx10_tables.TABLES))
            self.assertIn("Imported ", direct_out.getvalue())

            # CLI atomic write into missing nested directory, checking os.replace & 0 temps.
            real_replace = os.replace
            replaced_pairs: list[tuple[Path, Path]] = []

            def tracking_replace(src, dst):
                src_p, dst_p = Path(src), Path(dst)
                replaced_pairs.append((src_p, dst_p))
                self.assertEqual(src_p.parent.resolve(), dst_p.parent.resolve())
                self.assertEqual(src_p.suffix, ".tmp")
                return real_replace(src, dst)

            with (
                mock.patch.object(import_gfx10_tables, "SHA256", digest),
                mock.patch.object(import_gfx10_tables.os, "replace", side_effect=tracking_replace),
            ):
                code, out, err = _run_main(import_gfx10_tables, [str(rs_path), str(nested_out)])
            self.assertIs(type(code), int)
            self.assertEqual(code, 0, err)
            self.assertEqual(err, "")
            self.assertIn("Imported ", out)
            self.assertEqual(nested_out.read_text(encoding="utf-8"), generated)
            self.assertEqual([p.name for p in nested_out.parent.iterdir()], ["gfx1013_isa_tables.inl"])
            self.assertEqual(len(replaced_pairs), 1)

            # Overwrite stale file via argv=None forwarding sys.argv.
            nested_out.write_text("stale\n", encoding="utf-8")
            with (
                mock.patch.object(import_gfx10_tables, "SHA256", digest),
                mock.patch.object(sys, "argv", [str(TOOL), str(rs_path), str(nested_out)]),
            ):
                code_none, _, err_none = _run_main(import_gfx10_tables, None)
            self.assertEqual(code_none, 0, err_none)
            self.assertEqual(nested_out.read_text(encoding="utf-8"), generated)
            self.assertEqual(_tmp_files(nested_out.parent), [])


class ImportGfx10TablesNegativeAndMutationTests(unittest.TestCase):
    def _assert_clean_failure(
        self,
        argv: list[str],
        *,
        expected_code: int | None = 1,
        fragments: tuple[str, ...] = (),
        check_subprocess: bool = True,
        allow_stdout: bool = False,
    ) -> str:
        code, out, err = _run_main(import_gfx10_tables, argv)
        if expected_code is None:
            self.assertNotEqual(code, 0)
        else:
            self.assertEqual(code, expected_code, err)
        if not allow_stdout:
            self.assertEqual(out, "")
        self.assertNotIn("Traceback", err)
        self.assertTrue(err.strip())
        for fragment in fragments:
            self.assertIn(fragment.lower(), err.lower())

        if check_subprocess:
            proc = _run_subprocess(*argv)
            if expected_code is None:
                self.assertNotEqual(proc.returncode, 0)
            else:
                self.assertEqual(proc.returncode, expected_code, proc.stderr)
            if not allow_stdout:
                self.assertEqual(proc.stdout, "")
            self.assertNotIn("Traceback", proc.stderr)
            for fragment in fragments:
                self.assertIn(fragment.lower(), proc.stderr.lower())
        return err

    def test_sha256_mismatch_and_non_utf8_refused(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            rs_path = base / "opcodes.rs"
            rs_path.write_text(_build_synthetic_opcodes_rs(), encoding="utf-8")
            absent_out = base / "absent_dir" / "tables.inl"

            # Default SHA256 rejects synthetic opcodes.rs both in generate() and CLI/__main__.
            with self.assertRaises(ValueError):
                import_gfx10_tables.generate(rs_path)
            self._assert_clean_failure(
                [str(rs_path), str(absent_out)],
                expected_code=1,
                fragments=("9376fd6",),
            )
            self.assertFalse(absent_out.parent.exists())

            # __main__ entrypoint exits 1 cleanly without traceback.
            stdout_m, stderr_m = io.StringIO(), io.StringIO()
            with (
                mock.patch.object(sys, "argv", [str(TOOL), str(rs_path), str(absent_out)]),
                redirect_stdout(stdout_m),
                redirect_stderr(stderr_m),
                self.assertRaises(SystemExit) as exited,
            ):
                runpy.run_path(str(TOOL), run_name="__main__")
            self.assertEqual(exited.exception.code, 1)
            self.assertEqual(stdout_m.getvalue(), "")
            self.assertNotIn("Traceback", stderr_m.getvalue())
            self.assertIn("9376fd6", stderr_m.getvalue())

            # Non-UTF-8 bytes (even with matching SHA256) fail cleanly with 0 temps and preserved output.
            bad_bytes = b"// Each table\n\xff\xfe\x80\n"
            bad_digest = _sha256_lf(bad_bytes)
            bad_rs = base / "bad_utf8.rs"
            bad_rs.write_bytes(bad_bytes)
            existing_out = base / "existing.inl"
            existing_out.write_text("KEEP", encoding="utf-8")
            with self.assertRaises(UnicodeDecodeError):
                import_gfx10_tables.generate(bad_rs, expected_sha256=bad_digest)
            with mock.patch.object(import_gfx10_tables, "SHA256", bad_digest):
                self._assert_clean_failure(
                    [str(bad_rs), str(existing_out)],
                    expected_code=1,
                    fragments=("utf-8",),
                    check_subprocess=False,
                )
            self.assertEqual(existing_out.read_text(encoding="utf-8"), "KEEP")
            self.assertEqual(_tmp_files(base), [])

